'use strict';
const assert = require('node:assert/strict');
const { Firestore } = require('@google-cloud/firestore');
const { preview, commit, verify, HOUSING_FIELDS, RESET } = require('../../scripts/maintenance/normalize-shop-coupons');
assert.match(process.env.FIRESTORE_EMULATOR_HOST || '', /^127\.0\.0\.1:\d+$/);
const db = new Firestore({ projectId: 'demo-dj48-coupon-reset' });
(async () => {
  for (const id of ['new', 'used', 'high']) await db.doc('users/' + id).set({});
  await db.doc('coordiProfiles/used').set({ purchaseCoupons: 0, purchaseCouponGrant: 'welcome-20-v1', owned: ['kept'], prisms: { kept: { tone: 12 } } });
  await db.doc('coordiProfiles/high').set({ purchaseCoupons: 20 });
  await db.doc('userEconomy/used').set({ housingCoupons: 2, lastHousingCouponWeek: '2026-10-12', coupon10GrantedAt: 'old', djCoin: 123, other: 'kept' });
  const stale = await preview(db);
  await db.doc('coordiProfiles/high').update({ purchaseCoupons: 19 });
  await assert.rejects(commit(db, stale));
  assert.equal((await db.doc('coordiProfiles/used').get()).data().purchaseCoupons, 0, 'stale batch must write nothing');
  assert.equal((await db.doc('coordiProfiles/new').get()).exists, false);
  const plan = await preview(db);
  assert.equal((await commit(db, plan)).alreadyApplied, false);
  assert.deepEqual(await verify(db, plan), { shop: 3, housing: 1, exactlyTen: 3 });
  const profile = (await db.doc('coordiProfiles/used').get()).data();
  assert.deepEqual(profile.owned, ['kept']); assert.deepEqual(profile.prisms, { kept: { tone: 12 } });
  assert.equal(profile.purchaseCouponGrant, RESET);
  const economy = (await db.doc('userEconomy/used').get()).data();
  for (const field of HOUSING_FIELDS) assert(!Object.hasOwn(economy, field));
  assert.equal(economy.djCoin, 123); assert.equal(economy.other, 'kept');
  await db.doc('coordiProfiles/used').update({ purchaseCoupons: 9 });
  assert.equal((await commit(db, plan)).alreadyApplied, true);
  assert.equal((await db.doc('coordiProfiles/used').get()).data().purchaseCoupons, 9, 'rerun must never refill');
  console.log('PASS coupon reset: atomic conflict, exact 10, field deletion, ownership/coin preservation, retry without refill.');
})().finally(() => db.terminate()).catch(error => { console.error(error); process.exitCode = 1; });
