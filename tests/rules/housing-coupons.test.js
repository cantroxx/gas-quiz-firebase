const assert = require('node:assert/strict');
const { initializeApp } = require('firebase-admin/app');
const { getFirestore, FieldValue } = require('firebase-admin/firestore');
const { createCouponService } = require('../../functions/housing-coupons');
assert.ok(process.env.FIRESTORE_EMULATOR_HOST, 'Emulator required');
initializeApp({ projectId: 'demo-dj48-rules' });
const db = getFirestore();
const service = createCouponService({ db, FieldValue });
const monday = new Date('2026-09-20T15:00:00Z');
(async () => {
  const ref = db.collection('userEconomy').doc('coupon-test');
  await db.collection('users').doc('coupon-test').set({});
  await db.collection('users').doc('coupon-new').set({});
  await ref.set({ housingCoupons: 37, djCoin: 987, ownedItems: ['unchanged'] });
  await assert.rejects(service.resetMember('coupon-test', monday, () => { throw new Error('not-linked'); }), /not-linked/);
  assert.equal((await ref.get()).data().housingCoupons, 37);
  const results = await Promise.all(Array.from({ length: 8 }, () => service.resetMember('coupon-test', monday)));
  assert.equal(results.filter(result => result.granted).length, 0);
  assert.equal((await ref.get()).data().housingCoupons, 37);
  await ref.update({ housingCoupons: 0 });
  await service.resetAll(monday);
  assert.equal((await ref.get()).data().housingCoupons, 0);
  assert.equal((await db.collection('userEconomy').doc('coupon-new').get()).exists, false);
  await service.resetAll(new Date('2026-09-27T15:00:00Z'));
  const final = (await ref.get()).data();
  assert.equal(final.housingCoupons, 0);
  assert.equal(final.djCoin, 987);
  assert.deepEqual(final.ownedItems, ['unchanged']);
  assert.equal(final.lastHousingCouponWeek, undefined);
  console.log('PASS retired housing coupons: auth rejection, concurrent calls, no grants or writes, next week and coin preservation.');
  await db.terminate();
})().catch(error => { console.error(error); process.exitCode = 1; });
