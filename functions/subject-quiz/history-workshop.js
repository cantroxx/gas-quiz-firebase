function questions(u){if(!notes[u.id])return [];
 const V=require('./visual-scenes'),rows=events[u.id];
 return notes[u.id].flatMap(([goal,overreach,follow],i)=>{
  const e=rows[i],selected=[e,rows[(i+1)%rows.length],rows[(i+3)%rows.length]].sort((a,b)=>a[1]-b[1]);
  const letter=['가','나','다'][selected.indexOf(e)],others=notes[u.id].filter((_,j)=>j!==i).slice(0,3);
  const diagram=V.flow('사건과 변화의 흐름',selected.map((x,j)=>[`${['가','나','다'][j]} · ${x[0]}`,x[2]]),selected.map((x,j)=>`${['가','나','다'][j]}: ${x[0]}. ${x[2]}`).join(' '),'history-timeline');
  diagram.note='시간순으로 배치한 학습용 요약 · 간격은 실제 기간이 아니며 화살표가 원인을 뜻하지는 않습니다.';
  // Fit each historical summary at a readable size; no editorial teaching goal
  // or answer is printed in the student's material.
  const passage='아래 자료에서 사건과 특징을 연결해 읽으세요. 실제 사료의 인용이 아닌 학습용 요약입니다.';
  const meta={diagram,materialId:`${u.id}:history-visual-${i}`,objective:'history-event-'+e[0],contentTopics:['event:'+e[0]]};
  const make=(type,difficulty,prompt,correct,wrong,explanation)=>item(`${u.id}:history-${type}-${i}`,passage,prompt,correct,wrong,explanation,{...meta,difficulty,family:'history-'+type});
  return [
   make('focus',1,`자료 ${letter}의 사건과 설명을 연결한 탐구 주제로 적절한 것은?`,goal,others.map(x=>[x[0],`선택한 주제는 자료 ${letter}의 “${e[2]}”와 다른 사건·특징을 조사합니다. ${goal}.`]),`자료 ${letter}는 ${e[0]}입니다. “${e[2]}”라는 근거로 ${goal}.`),
   make('overreach',3,'이 흐름도에 제시된 사실만으로 뒷받침할 수 없는 해석은?',overreach,selected.map(x=>[x[2],`이 설명은 자료에 있는 ${x[0]}의 내용입니다. 확인한 사실과 자료를 넘어선 해석을 구별하세요.`]),`${overreach.replace(/고 본다$/,'는 결론은')} 자료만으로 확정할 수 없습니다. ${follow}.`),
   make('investigation',2,`자료 ${letter}를 보고 “${overreach}”라고 해석했습니다. 이를 직접 검토할 조사는?`,follow,others.map(x=>[x[2],`이 조사는 자료 ${letter}의 해당 주장을 직접 확인하는 데 필요한 근거와 다릅니다. ${follow}.`]),`조사 질문과 자료가 맞아야 합니다. ${follow}.`)

  ];
 });
}
