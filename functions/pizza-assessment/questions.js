function rational(value) {
  if (typeof value !== 'string' || value.length > 32) return null;
  const s = value.normalize('NFKC').trim();
  const m = s.match(/^(?:(\d{1,3})\s+)?(\d{1,3})\s*\/\s*(\d{1,3})$/);
  if (m) { const d = Number(m[3]); return d > 0 ? [Number(m[1] || 0) * d + Number(m[2]), d] : null; }
  return /^\d{1,3}$/.test(s) ? [Number(s), 1] : null;
}
function isCorrect(q, value) {
  if (q.choices) return value === q.answer;
  const a = rational(value), b = rational(q.answer);
  if (!a || !b || a[0] * b[1] !== b[0] * a[1]) return false;
  if (q.mixedOnly) { const m = value.trim().match(/^(\d+)\s+(\d+)\s*\/\s*(\d+)$/); return !!m && Number(m[1]) > 0 && Number(m[2]) > 0 && Number(m[2]) < Number(m[3]); }
  return true;
}
const publicQuestions = (set = questions) => set.map(({ answer, feedback, ...q }) => q);
function grade(answers, set = questions) {
  const items = set.map(q => ({ ...q, response: answers[q.id - 1] || '', correct: isCorrect(q, answers[q.id - 1] || '') }));
  return { score: items.filter(q => q.correct).length * 4, correct: items.filter(q => q.correct).length, items };
}
