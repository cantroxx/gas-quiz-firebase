  // 문제 목록에서 하나 뽑아 보기 순서를 섞는다 (원본은 c[0]이 정답)
  function serveFrom(list, key0, unitLabel) {
    let q = null, key = '';
    for (let i = 0; i < 8; i++) {
      const cand = list[R(list.length)];
      key = key0 + '|' + cand.q;
      if (!recent.includes(key)) { q = cand; break; }
      q = cand;
    }
    remember(key);
    const idx = [0, 1, 2, 3];
    for (let i = idx.length - 1; i > 0; i--) {
      const j = R(i + 1);
      [idx[i], idx[j]] = [idx[j], idx[i]];
    }
    return {
      unit: unitLabel,
      text: q.q,
      choices: idx.map((i) => q.c[i]),
      answerIndex: idx.indexOf(0),
    };
  }

