#!/usr/bin/env python3
"""Rebuild the offline review catalog from curated metadata and screenshot crops.

No downloads, production writes, or game runtime changes. Contact sheets must
already exist and every selected item must have a matching preview-index entry.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs/product/popular-image-selection-2026-10-18'
data = json.loads((OUT / 'selection.json').read_text())
previews = json.loads((OUT / 'preview-index.json').read_text())
rows = []
for row in data['selected']:
    preview = previews[row['id']]
    assert (OUT / preview['sheet']).is_file(), preview['sheet']
    rows.append({**{key: row[key] for key in (
        'id', 'category', 'questionKind', 'group', 'groupLabel', 'answer',
        'aliases', 'prompt', 'sourceName', 'sourceUrl', 'imageUrl')},
        'rating': row.get('rating'), 'preview': preview})
payload = {'version': data['version'], 'summary': data['summary'], 'rows': rows}
(OUT / 'review-data.js').write_text(
    '// Generated by scripts/audit/build-popular-image-review.py\n'
    'window.POPULAR_REVIEW = ' + json.dumps(payload, ensure_ascii=False) + ';\n')
print(f'Offline review catalog: {len(rows)} questions')
