'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../../..');
const policy=require('../../../functions/word-bomb/word-policy');
const input=process.argv[2];
if(!input)throw Error('Usage: node scripts/audit/word-bomb/build_dictionary.js extracted-nikl-nouns.json');
const source=JSON.parse(fs.readFileSync(input,'utf8'));
const seed=JSON.parse(fs.readFileSync(path.join(root,'fixtures/word-bomb/classroom-seed-v1.json'),'utf8'));
const allowed=w=>/^[가-힣]{2,100}$/.test(w)&&!policy.isBlocked(w);
const entries=new Map();
for(const word of seed)if(allowed(word))entries.set(word,{word,grade:0,source:'classroom-v1'});
for(const row of source.words)if(row.grade<=3&&allowed(row.word))entries.set(row.word,{...row,source:'NIKL'});
// Sample the next grade across the alphabet; do not truncate all words after a letter.
const digest=word=>crypto.createHash('sha256').update('word-bomb-v2:'+word).digest('hex');
const extra=source.words.filter(row=>row.grade===4&&allowed(row.word)&&!entries.has(row.word)).sort((a,b)=>digest(a.word).localeCompare(digest(b.word)));
for(const row of extra){if(entries.size>=10000)break;entries.set(row.word,{...row,source:'NIKL'});}
if(entries.size!==10000)throw Error('Expected 10,000 unique entries, got '+entries.size);
// Preserve the base 10,000 words and add reviewed omissions without evicting words.
for(const word of ['산성비']) {
  const row=source.words.find(row=>row.word===word);
  if(!row || !allowed(word)) throw Error('Missing reviewed noun: '+word);
  entries.set(word,{...row,source:'NIKL'});
}
const rows=[...entries.values()].sort((a,b)=>a.word.localeCompare(b.word,'ko'));
const words=rows.map(row=>row.word),counts={};for(const row of rows)counts[row.source==='NIKL'?'grade'+row.grade:'classroom']=(counts[row.source==='NIKL'?'grade'+row.grade:'classroom']||0)+1;
const wordHash=crypto.createHash('sha256').update(words.join('\n')+'\n').digest('hex');
const notice={source:source.source,sourceUrl:source.sourceUrl,license:source.license,inputSha256:source.inputSha256,sheet:source.sheet,columns:source.columns,selection:'All eligible grades 1–3 nouns plus classroom-v1; deterministic sha256 sample of grade 4 to 10,000. Reviewed supplement: 산성비. Exact/substring classroom exclusions; no definitions copied.',count:words.length,counts,wordSha256:wordHash};
fs.writeFileSync(path.join(root,'fixtures/word-bomb/dictionary-v2-provenance.json'),JSON.stringify({...notice,entries:rows.map(r=>[r.word,r.grade,r.source])},null,2)+'\n');
const lines=[];for(let i=0;i<words.length;i+=12)lines.push(words.slice(i,i+12).join(' '));
const output=`/* Generated by scripts/audit/word-bomb/build_dictionary.js.
 * Source: National Institute of Korean Language (2024), KOGL Type 1.
 * ${source.sourceUrl}
 * Includes original classroom-v1 vocabulary; see DICTIONARY_NOTICE.md. */
(function(root){
  'use strict';
  const words=\`\n${lines.join('\n')}\n\`.trim().split(/\\s+/);
  const api={version:'nikl-classroom-10001-v3',words,sourceUrl:${JSON.stringify(source.sourceUrl)},license:'KOGL Type 1'};
  if(typeof module!=='undefined')module.exports=api;else root.WordBombDictionary=api;
})(typeof globalThis!=='undefined'?globalThis:this);
`;
fs.writeFileSync(path.join(root,'functions/word-bomb/dictionary.js'),output);
console.log(JSON.stringify(notice,null,2));
