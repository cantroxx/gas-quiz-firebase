"use strict";
const fs = require("node:fs"),
  path = require("node:path"),
  crypto = require("node:crypto");
const root = path.resolve(__dirname, "../../..");
const policy = require("../../../functions/word-bomb/word-policy");
const [standardFile, basicFile] = process.argv.slice(2);
if (!standardFile || !basicFile)
  throw Error(
    "Usage: node build_expanded_dictionary.js stdict-nouns.json nikl-nouns.json",
  );
const standard = JSON.parse(fs.readFileSync(standardFile)),
  basic = JSON.parse(fs.readFileSync(basicFile));
const previous = require("../../../fixtures/word-bomb/dictionary-v2-provenance.json");
const allowed = (w) => /^[가-힣]{2,100}$/.test(w) && !policy.isBlocked(w);
const digest = (s) => crypto.createHash("sha256").update(s).digest("hex");
const base = previous.entries.map((r) => r[0]);
if (base.length !== 10001 || base.some((w) => !allowed(w)))
  throw Error("Original dictionary mismatch");
const words = new Set(base),
  practiceWords = [...base],
  extraBasic = [];
for (const row of basic.words)
  if (allowed(row.word) && !words.has(row.word)) {
    words.add(row.word);
    extraBasic.push(row.word);
  }
const unique = new Map();
for (const row of standard.entries) {
  const [word, id, general, cats] = row;
  if (!allowed(word) || words.has(word)) continue;
  const prior = unique.get(word);
  if (!prior || general > prior[2]) unique.set(word, [word, id, general, cats]);
}
const reviewedTerms = new Set(require('../../../fixtures/word-bomb/reviewed-school-terms.json'));
const ranked = [...unique.values()]
  .map((r) => ({ row: r, hash: digest("word-bomb-100k:" + r[0]) }))
  .sort(
    (a, b) =>
      Number(reviewedTerms.has(b.row[0])) - Number(reviewedTerms.has(a.row[0])) ||
      b.row[2] - a.row[2] ||
      Number(a.row[0].length > 6) - Number(b.row[0].length > 6) ||
      a.hash.localeCompare(b.hash),
  );
const selected = [];
for (const { row } of ranked) {
  if (words.size >= 100000) break;
  words.add(row[0]);
  selected.push(row);
}
if (words.size !== 100000) throw Error("Need 100000 words, got " + words.size);
const sorted = [...words].sort((a, b) => a.localeCompare(b, "ko"));
const wordHash = digest(sorted.join("\n") + "\n");
const provenance = {
  version: "nikl-stdict-classroom-100000-v4",
  count: sorted.length,
  baseCount: base.length,
  extraBasicCount: extraBasic.length,
  extraStandardCount: selected.length,
  practiceCount: practiceWords.length,
  wordSha256: wordHash,
  basicSource: basic.sourceUrl,
  standardSource: standard.sourceUrl,
  mirror: standard.mirror,
  mirrorCommit: standard.commit,
  license: standard.license,
  selection:
    "Preserve v3; add all eligible NIKL basic nouns; add normal standard nouns, general senses then <=6 syllables first with deterministic sha256 order. Normalize hyphens/carets; merge homonyms; exclude obsolete/nonstandard/only proper-name/sexual/slur definitions and classroom policy exclusions. No definitions or examples distributed.",
  inputSha256: {
    standard: digest(fs.readFileSync(standardFile)),
    basic: digest(fs.readFileSync(basicFile)),
  },
  files: standard.files,
  extraBasic,
  standardEntries: selected,
};
fs.writeFileSync(
  path.join(root, "fixtures/word-bomb/dictionary-v4-provenance.json"),
  JSON.stringify(provenance, null, 2) + "\n",
);
const lines = (a) =>
  Array.from({ length: Math.ceil(a.length / 12) }, (_, i) =>
    a.slice(i * 12, i * 12 + 12).join(" "),
  ).join("\n");
fs.writeFileSync(
  path.join(root, "functions/word-bomb/dictionary.js"),
  `/* Generated by scripts/audit/word-bomb/build_expanded_dictionary.js.
 * National Institute of Korean Language; basic vocabulary (KOGL Type 1), standard dictionary (CC BY-SA 2.0 KR).
 * Standard source mirror commit ${standard.commit}. Word list is CC BY-SA 2.0 KR; see DICTIONARY_NOTICE.md. */
(function(root){'use strict';
const words=\`\n${lines(sorted)}\n\`.trim().split(/\\s+/);
const practiceWords=\`\n${lines(practiceWords)}\n\`.trim().split(/\\s+/);
const api={version:'${provenance.version}',words,practiceWords,sourceUrl:'https://stdict.korean.go.kr/',license:'CC BY-SA 2.0 KR'};
if(typeof module!=='undefined')module.exports=api;else root.WordBombDictionary=api;
})(typeof globalThis!=='undefined'?globalThis:this);
`,
);
fs.writeFileSync(
  path.join(root, "public/word-bomb/word-list.txt"),
  sorted.join("\n") + "\n",
);
console.log(
  JSON.stringify({
    count: sorted.length,
    basicAdded: extraBasic.length,
    standardAdded: selected.length,
    practice: practiceWords.length,
    wordHash,
  }),
);
