#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),C=require('../functions/subject-quiz/curriculum');
const data={version:C.VERSION,subjects:C.subjects,legacyQuizIds:C.legacyQuizIds,legacyCategoryKeys:C.legacyCategoryKeys};
const out=`/* Generated by scripts/build-subject-quiz-catalog.js. */
(function(root){
  const data=${JSON.stringify(data,null,2)};
  data.isLegacyRecord=row=>data.legacyQuizIds.includes(row?.quizId)||data.legacyCategoryKeys.includes(row?.categoryKey||row?.category);
  data.targetForQuiz=id=>{
    const q=root.DJ48QuizCatalog?.QUIZ_CATALOG[id];
    if(String(id).startsWith('generated-')&&q?.standalonePath)return q.standalonePath;
    if(!data.legacyQuizIds.includes(id)||!q)return null;
    return '/subject-quiz/?subject='+q.subjectId+(id==='spelling'?'&group=spelling':'');
  };
  data.labelForQuiz=id=>{
    const q=root.DJ48QuizCatalog?.QUIZ_CATALOG[id];
    if(!data.legacyQuizIds.includes(id))return q?.title||id;
    if(id==='spelling')return '초등 맞춤법';
    const subject=data.subjects.find(s=>s.id===q?.subjectId);
    return subject ? subject.title+(subject.id==='korean'?' · 4학년 단원':' · 생성 퀴즈') : q?.title||id;
  };
  const catalog=root.DJ48QuizCatalog;
  if(catalog)for(const subject of data.subjects){
    const groups=subject.groups.filter(g=>!g.parent);
    if(subject.groups.some(g=>g.parent))groups.push({id:'korean-history',title:'역사',description:'한국사 · 세계사'});
    const ids=groups.map(group=>{
      const id='generated-'+subject.id+'-'+group.id;
      catalog.QUIZ_CATALOG[id]={title:group.title,icon:subject.icon,subjectId:subject.id,
        desc:group.description||subject.publisher+' · 단원별로 새 문제를 풀어 보세요.',
        standalonePath:'/subject-quiz/?subject='+subject.id+'&group='+group.id,modes:[]};
      return id;
    });
    Object.assign(catalog.SUBJECT_CATALOG[subject.id],{quizzes:ids,desc:'단원별 생성 문제로 연습하고 과목 통합 랭킹에 도전해요.',cardDesc:'연습전 · 랭킹전 · 단원별 문제 생성'});
  }
  root.DJ48SubjectQuiz=data;
})(window);
`;
const target=path.resolve(__dirname,'../public/js/data/subject-quiz-catalog.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('Subject catalog must be rebuilt');}
else fs.writeFileSync(target,out);
